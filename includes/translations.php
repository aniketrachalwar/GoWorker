/**
 * Translates a key based on current page language session.
 * Fallback to English if key or language translation is missing.
 * 
 * @param string $key
 * @return string
 */
function __($key) {
    $current_lang = isset($_SESSION['lang']) ? $_SESSION['lang'] : 'en';
    
    if (isset($GLOBALS['translations'][$current_lang][$key])) {
        return $GLOBALS['translations'][$current_lang][$key];
    }
    
    // Fallback to English
    if (isset($GLOBALS['translations']['en'][$key])) {
        return $GLOBALS['translations']['en'][$key];
    }
    
    return $key;
}
